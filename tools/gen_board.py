#!/usr/bin/env python3
"""Generate viewer/scenes/board.x3d: one 8x8 board, eval bar, one placeholder piece.

Addressing convention (see docs/X3D-MAPPING.md): every square is DEF'd sq_<file><rank>
(sq_a1..sq_h8), every piece piece_<square>, the eval bar evalbar. The SAI layer
(viewer/js) finds nodes by these names, so they are a stable contract.
"""
import sys
from pathlib import Path

out = Path(sys.argv[1] if len(sys.argv) > 1 else "viewer/scenes/board.x3d")
SZ = 1.0
rows = []
for r in range(8):
    for f in range(8):
        name = "abcdefgh"[f] + str(r + 1)
        light = (f + r) % 2 == 1
        app = "USE='lightApp'" if light else "USE='darkApp'"
        x, z = (f - 3.5) * SZ, (3.5 - r) * SZ
        rows.append(
            f"      <Transform DEF='sq_{name}' translation='{x} 0 {z}'>\n"
            f"        <Shape><Appearance {app}/><Box size='{SZ} 0.1 {SZ}'/></Shape>\n"
            f"      </Transform>"
        )
# first occurrence must carry the DEF; patch the first light and first dark tile
squares = "\n".join(rows)
squares = squares.replace("<Appearance USE='darkApp'/>",
    "<Appearance DEF='darkApp'><Material diffuseColor='0.18 0.2 0.3' emissiveColor='0.02 0.03 0.06'/></Appearance>", 1)
squares = squares.replace("<Appearance USE='lightApp'/>",
    "<Appearance DEF='lightApp'><Material diffuseColor='0.75 0.8 0.9' emissiveColor='0.05 0.06 0.08'/></Appearance>", 1)

doc = f"""<?xml version="1.0" encoding="UTF-8"?>
<X3D profile='Interchange' version='4.0' xmlns:xsd='http://www.w3.org/2001/XMLSchema-instance' xsd:noNamespaceSchemaLocation='https://www.web3d.org/specifications/x3d-4.0.xsd'>
  <head>
    <meta name='title' content='x3d.chess board scaffold'/>
    <meta name='description' content='8x8 board, eval bar and one placeholder piece. Generated by tools/gen_board.py.'/>
    <meta name='license' content='GPL-3.0-or-later'/>
  </head>
  <Scene>
    <NavigationInfo type='"EXAMINE" "ANY"'/>
    <Viewpoint DEF='vp_overview' position='0 9 9' orientation='1 0 0 -0.78' description='Overview'/>
    <DirectionalLight direction='-0.3 -1 -0.4' intensity='0.9'/>
    <Group DEF='board'>
{squares}
    </Group>
    <Transform DEF='piece_e2' translation='0.5 0.35 2.5'>
      <Shape><Appearance><Material diffuseColor='0 0.9 1' emissiveColor='0 0.25 0.3'/></Appearance><Cylinder radius='0.25' height='0.6'/></Shape>
    </Transform>
    <Transform DEF='evalbar' translation='-5 0.5 0' scale='1 1 1'>
      <Shape><Appearance><Material diffuseColor='0.9 0.9 0.9'/></Appearance><Box size='0.3 1 8'/></Shape>
    </Transform>
  </Scene>
</X3D>
"""
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(doc)
print(f"wrote {out} ({len(rows)} squares)")
